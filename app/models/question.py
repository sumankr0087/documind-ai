"""Question answering request and response models."""
from typing import List, Optional
from pydantic import BaseModel, Field


class QuestionRequest(BaseModel):
    """Request payload for question answering."""

    question: str = Field(..., min_length=2, max_length=2000, description="The user question to answer")
    document_id: Optional[str] = Field(None, description="Optional document ID filter to scope retrieval")
    top_k: Optional[int] = Field(None, ge=1, le=20, description="Number of relevant chunks to retrieve (default: 5)")


class Citation(BaseModel):
    """Citation referencing a specific chunk used as evidence."""

    chunk_id: str = Field(..., description="Unique chunk ID")
    document_id: str = Field(..., description="Document ID that provided evidence")
    filename: str = Field(..., description="Source document filename")
    page_number: Optional[int] = Field(None, description="Page number where evidence appears (if applicable)")
    snippet: str = Field(..., description="Excerpt of the retrieved context")
    relevance_score: float = Field(..., description="Similarity relevance score (higher is more similar)")


class QuestionResponse(BaseModel):
    """Answer response generated by RAG pipeline."""

    question: str = Field(..., description="Original user question")
    answer: str = Field(..., description="Grounded answer generated from retrieved context")
    citations: List[Citation] = Field(default_factory=list, description="Citations supporting the answer")
    evidence_sufficient: bool = Field(
        ...,
        description="Indicates whether retrieved context contained sufficient evidence to answer",
    )
    document_id: Optional[str] = Field(None, description="Scoping document ID if filtered")
    model_used: str = Field(..., description="LLM model or engine used to formulate the answer")
